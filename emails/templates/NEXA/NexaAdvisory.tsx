import React from 'react';
import { CanonicalLayout } from '../../components/CanonicalLayout';
import { KeyFactsBlock } from '../../components/KeyFactsBlock';
import { CanonicalEmailPayload } from '../../types/CanonicalEmail';
import { Text } from '@react-email/components';

export interface NexaAdvisoryData {
  recipient_first_name?: string;
  advisory_title_display: string;
  advisory_severity_display: string;
  advisory_summary_display: string;
  [key: string]: any;
}

export interface NexaAdvisoryEmailProps {
  payload: CanonicalEmailPayload;
}

export const NexaAdvisoryEmail: React.FC<NexaAdvisoryEmailProps> = ({ payload }) => {
  const data = payload.eventData as NexaAdvisoryData;
  const firstName = data?.recipient_first_name || 'there';

  const facts = [
    { label: 'Advisory', value: data?.advisory_title_display || 'See portal' },
    { label: 'Severity', value: data?.advisory_severity_display || 'Informational' },
    { label: 'Summary', value: data?.advisory_summary_display || 'See full advisory' },
    { label: 'Reference', value: payload.traceability.message_reference },
    { label: 'Date and time', value: `${payload.localizedValues.date_local} (${payload.localizedValues.date_utc} UTC)` },
  ];

  return (
    <CanonicalLayout
      payload={payload}
      subject="Nexa AI advisory notice for your account"
      preheader="Nexa has issued an advisory that may require your attention."
      openingText={`Hello ${firstName}, Nexa AI has issued an advisory relevant to your ZoikoNex account.`}
      primaryCtaText="View advisory"
      primaryCtaLink={`https://zoikonex.com/nexa/advisories?ref=${payload.traceability.message_reference}`}
    >
      <KeyFactsBlock facts={facts} />

      <Text style={actionCopy}>
        Select <strong>View advisory</strong> to review the full AI-generated advisory, evidence and recommended actions.
      </Text>

      <Text style={protectionCopy}>
        This advisory was generated by Nexa AI. AI-generated content should be reviewed against your specific business context before acting.
      </Text>
    </CanonicalLayout>
  );
};

export default NexaAdvisoryEmail;

const actionCopy = {
  fontSize: '14px',
  color: '#484848',
  lineHeight: '1.5',
  marginTop: '16px',
};

const protectionCopy = {
  fontSize: '14px',
  color: '#484848',
  lineHeight: '1.5',
  marginTop: '16px',
  padding: '12px',
  backgroundColor: '#f5f3ff',
  borderLeft: '4px solid #8b5cf6',
};
