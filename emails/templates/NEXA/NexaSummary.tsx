import React from 'react';
import { CanonicalLayout } from '../../components/CanonicalLayout';
import { KeyFactsBlock } from '../../components/KeyFactsBlock';
import { CanonicalEmailPayload } from '../../types/CanonicalEmail';
import { Text } from '@react-email/components';

export interface NexaSummaryData {
  recipient_first_name?: string;
  summary_period_display: string;
  summary_headline_display: string;
  key_metric_display: string;
}

export interface NexaSummaryEmailProps {
  payload: CanonicalEmailPayload;
}

export const NexaSummaryEmail: React.FC<NexaSummaryEmailProps> = ({ payload }) => {
  const data = payload.eventData as NexaSummaryData;
  const firstName = data?.recipient_first_name || 'there';

  const facts = [
    { label: 'Period', value: data?.summary_period_display || 'Unknown' },
    { label: 'Headline insight', value: data?.summary_headline_display || 'See full summary' },
    { label: 'Key metric', value: data?.key_metric_display || 'See report' },
    { label: 'Reference', value: payload.traceability.message_reference },
    { label: 'Date and time', value: `${payload.localizedValues.date_local} (${payload.localizedValues.date_utc} UTC)` },
  ];

  return (
    <CanonicalLayout
      payload={payload}
      subject="Your Nexa AI summary is ready"
      preheader="Nexa has prepared an AI-generated summary for your account."
      openingText={`Hello ${firstName}, Nexa AI has generated a summary for your ZoikoNex account.`}
      primaryCtaText="View full summary"
      primaryCtaLink={`https://zoikonex.com/nexa/summaries?ref=${payload.traceability.message_reference}`}
    >
      <KeyFactsBlock facts={facts} />

      <Text style={actionCopy}>
        Select <strong>View full summary</strong> to explore the complete AI-generated analysis and supporting data.
      </Text>

      <Text style={protectionCopy}>
        This summary was generated by Nexa AI. For your security, this email does not display full payment credentials, identity documents, SIM credentials or complete account identifiers.
      </Text>
    </CanonicalLayout>
  );
};

export default NexaSummaryEmail;

const actionCopy = {
  fontSize: '14px',
  color: '#484848',
  lineHeight: '1.5',
  marginTop: '16px',
};

const protectionCopy = {
  fontSize: '14px',
  color: '#484848',
  lineHeight: '1.5',
  marginTop: '16px',
  padding: '12px',
  backgroundColor: '#f5f3ff',
  borderLeft: '4px solid #8b5cf6',
};
