import React from 'react';
import { CanonicalLayout } from '../../components/CanonicalLayout';
import { KeyFactsBlock } from '../../components/KeyFactsBlock';
import { CanonicalEmailPayload } from '../../types/CanonicalEmail';
import { Text } from '@react-email/components';

export interface NexaRecommendationData {
  recipient_first_name?: string;
  recommendation_title_display: string;
  recommendation_category_display: string;
  potential_impact_display: string;
}

export interface NexaRecommendationEmailProps {
  payload: CanonicalEmailPayload;
}

export const NexaRecommendationEmail: React.FC<NexaRecommendationEmailProps> = ({ payload }) => {
  const data = payload.eventData as NexaRecommendationData;
  const firstName = data?.recipient_first_name || 'there';

  const facts = [
    { label: 'Recommendation', value: data?.recommendation_title_display || 'See portal' },
    { label: 'Category', value: data?.recommendation_category_display || 'General' },
    { label: 'Potential impact', value: data?.potential_impact_display || 'See details' },
    { label: 'Reference', value: payload.traceability.message_reference },
    { label: 'Date and time', value: `${payload.localizedValues.date_local} (${payload.localizedValues.date_utc} UTC)` },
  ];

  return (
    <CanonicalLayout
      payload={payload}
      subject="Nexa AI has a recommendation for your account"
      preheader="Nexa has identified an actionable recommendation. Review it now."
      openingText={`Hello ${firstName}, Nexa AI has identified a recommendation that may benefit your ZoikoNex account.`}
      primaryCtaText="View recommendation"
      primaryCtaLink={`https://zoikonex.com/nexa/recommendations?ref=${payload.traceability.message_reference}`}
    >
      <KeyFactsBlock facts={facts} />

      <Text style={actionCopy}>
        Select <strong>View recommendation</strong> to review the full details, supporting rationale and available actions.
      </Text>

      <Text style={protectionCopy}>
        This recommendation was generated by Nexa AI. AI-generated content should be reviewed against your specific business context before acting.
      </Text>
    </CanonicalLayout>
  );
};

export default NexaRecommendationEmail;

const actionCopy = {
  fontSize: '14px',
  color: '#484848',
  lineHeight: '1.5',
  marginTop: '16px',
};

const protectionCopy = {
  fontSize: '14px',
  color: '#484848',
  lineHeight: '1.5',
  marginTop: '16px',
  padding: '12px',
  backgroundColor: '#f5f3ff',
  borderLeft: '4px solid #8b5cf6',
};
